"""Evaluate ReliefLink's two AI components and write eval/RESULTS.md.

1. Triage accuracy on a labeled set of messages (English, Hindi, Tamil,
   romanized Hindi/Tamil). The key safety metric is UNDER-TRIAGE: a truly
   critical message ranked below HIGH could mean a rescue team goes elsewhere.
2. Dispatch quality: optimal (Hungarian) vs first-come-first-served, averaged
   over many randomly generated flood scenarios.

Run:  python -m eval.evaluate
"""

from __future__ import annotations

import csv
import random
from collections import Counter, defaultdict
from pathlib import Path
from statistics import mean

from app.matching import greedy_dispatch, optimal_dispatch, summarize
from app.triage import triage

HERE = Path(__file__).resolve().parent
LEVELS = ["LOW", "MEDIUM", "HIGH", "CRITICAL"]


def evaluate_triage(filename: str):
    rows = list(csv.DictReader(open(filename, encoding="utf-8")))
    cat_ok = level_exact = level_within_one = 0
    critical_total = critical_caught = under_triaged = critical_low = flagged = 0
    confusion = defaultdict(Counter)
    misses = []
    for row in rows:
        r = triage(row["text"])
        confusion[row["category"]][r.category] += 1
        cat_ok += r.category == row["category"]
        true_i, pred_i = LEVELS.index(row["level"]), LEVELS.index(r.level)
        level_exact += true_i == pred_i
        level_within_one += abs(true_i - pred_i) <= 1
        if row["level"] == "CRITICAL":
            critical_total += 1
            if pred_i >= LEVELS.index("HIGH"):
                critical_caught += 1
            else:
                under_triaged += 1
            critical_low += r.level == "LOW"
        flagged += r.needs_review
        if r.category != row["category"] or abs(true_i - pred_i) > 1:
            misses.append((row["text"], row["category"], row["level"], r.category, r.level))
    n = len(rows)
    return {
        "n": n,
        "category_accuracy": cat_ok / n,
        "level_exact": level_exact / n,
        "level_within_one": level_within_one / n,
        "critical_total": critical_total,
        "critical_recall_high_or_above": critical_caught / critical_total,
        "under_triaged": under_triaged,
        "critical_low": critical_low,
        "flagged": flagged,
        "confusion": confusion,
        "misses": misses,
    }


# Rough bounding box of Chennai.
LAT, LON = (12.90, 13.15), (80.10, 80.30)
CATEGORY_MIX = ["rescue"] * 3 + ["medical"] * 3 + ["food"] * 2 + ["water"] * 2 + ["shelter"]
SKILL_SETS = [["rescue"], ["rescue", "medical"], ["medical"], ["supplies"], ["supplies", "transport"], ["transport"]]


def random_scenario(rng: random.Random, n_requests=40, n_volunteers=14):
    requests = []
    for i in range(n_requests):
        cat = rng.choice(CATEGORY_MIX)
        base = {"rescue": 60, "medical": 55, "food": 35, "water": 35, "shelter": 25}[cat]
        requests.append({
            "id": i, "category": cat,
            "urgency": max(5, min(100, int(rng.gauss(base, 18)))),
            "lat": rng.uniform(*LAT), "lon": rng.uniform(*LON),
            "created_at": f"2026-01-01T{8 + i // 6:02d}:{(i * 7) % 60:02d}:00",
        })
    volunteers = [{
        "id": j, "skills": rng.choice(SKILL_SETS), "capacity": rng.choice([1, 1, 2, 2, 3]),
        "lat": rng.uniform(*LAT), "lon": rng.uniform(*LON),
    } for j in range(n_volunteers)]
    return volunteers, requests


def evaluate_dispatch(runs=200, seed=7):
    rng = random.Random(seed)
    results = {"optimal": defaultdict(list), "greedy": defaultdict(list)}
    for _ in range(runs):
        vols, reqs = random_scenario(rng)
        for name, fn in (("optimal", optimal_dispatch), ("greedy", greedy_dispatch)):
            s = summarize(fn(vols, reqs), reqs)
            crit_rate = s["critical_served"] / s["critical_total"] if s["critical_total"] else 1.0
            for k, v in (("critical_served_rate", crit_rate), ("urgency_served", s["urgency_served"]),
                         ("requests_served", s["requests_served"]), ("km_per_assignment", s["total_km"] / max(1, s["requests_served"])),
                         ("avg_eta_min", s["avg_eta_min"])):
                results[name][k].append(v)
    return {name: {k: mean(v) for k, v in metrics.items()} for name, metrics in results.items()}, runs


def pct(a, b):
    return (a - b) / b * 100 if b else 0.0


def main():
    dev = evaluate_triage(HERE.parent / "data" / "triage_training.csv")
    t = evaluate_triage(HERE / "heldout_messages.csv")
    d, runs = evaluate_dispatch()
    o, g = d["optimal"], d["greedy"]

    def row(label, key, fmt="{:.0%}"):
        return f"| {label} | {fmt.format(dev[key])} | **{fmt.format(t[key])}** |"

    cats = sorted(t["confusion"])
    lines = [
        "# ReliefLink evaluation results",
        "",
        "Generated by `python -m eval.evaluate`.",
        "",
        "## 1. Triage",
        "",
        "Two labeled sets of messages in English, Hindi, Tamil and romanized Hindi/Tamil. Both were "
        "written by the author and are **not** real disaster data.",
        "",
        f"- **Development set** ({dev['n']} messages, `data/triage_training.csv`): used to tune the lexicon "
        "and to train the fallback classifier. Its scores are optimistic by construction.",
        f"- **Held-out set** ({t['n']} messages, `heldout_messages.csv`): written and labeled *before* "
        "being run, never used for tuning. **These are the numbers that matter.**",
        "",
        "| Metric | Development | Held-out |",
        "|---|---|---|",
        row("Need category accuracy", "category_accuracy"),
        row("Urgency level exact match", "level_exact"),
        row("Urgency level within one step", "level_within_one"),
        f"| Critical messages ranked HIGH or CRITICAL (safety recall) | "
        f"{dev['critical_recall_high_or_above']:.0%} ({dev['critical_total'] - dev['under_triaged']}/{dev['critical_total']}) | "
        f"**{t['critical_recall_high_or_above']:.0%}** ({t['critical_total'] - t['under_triaged']}/{t['critical_total']}) |",
        f"| Critical messages ranked LOW (worst case) | {dev['critical_low']} | **{t['critical_low']}** |",
        f"| Messages flagged for human review | {dev['flagged']} | {t['flagged']} |",
        "",
        "Held-out confusion matrix (rows = true category, columns = predicted):",
        "",
        "| true \\ pred | " + " | ".join(cats) + " |",
        "|---|" + "---|" * len(cats),
    ]
    for c in cats:
        lines.append(f"| **{c}** | " + " | ".join(str(t["confusion"][c][p]) for p in cats) + " |")
    lines += ["", "### Held-out errors (wrong category, or urgency off by 2+ levels)", ""]
    if t["misses"]:
        lines += ["| Message | True | Predicted |", "|---|---|---|"]
        for text, tc, tl, pc, pl in t["misses"]:
            lines.append(f"| {text} | {tc} / {tl} | {pc} / {pl} |")
    else:
        lines.append("None.")

    lines += [
        "",
        "## 2. Dispatch: optimal assignment vs first-come-first-served",
        "",
        f"Averaged over **{runs} random flood scenarios** across Chennai (40 requests, 14 volunteers "
        "with mixed skills and capacities each). Both strategies respect skills, capacity and a 15 km limit.",
        "",
        "| Metric (mean per scenario) | Optimal (Hungarian) | First-come-first-served | Change |",
        "|---|---|---|---|",
        f"| Critical requests served | {o['critical_served_rate']:.1%} | {g['critical_served_rate']:.1%} | "
        f"{(o['critical_served_rate'] - g['critical_served_rate']) * 100:+.1f} pts |",
        f"| Total urgency served | {o['urgency_served']:.0f} | {g['urgency_served']:.0f} | {pct(o['urgency_served'], g['urgency_served']):+.1f}% |",
        f"| Requests served | {o['requests_served']:.1f} | {g['requests_served']:.1f} | {pct(o['requests_served'], g['requests_served']):+.1f}% |",
        f"| Travel per assignment (km) | {o['km_per_assignment']:.2f} | {g['km_per_assignment']:.2f} | {pct(o['km_per_assignment'], g['km_per_assignment']):+.1f}% |",
        f"| Average ETA (min) | {o['avg_eta_min']:.1f} | {g['avg_eta_min']:.1f} | {pct(o['avg_eta_min'], g['avg_eta_min']):+.1f}% |",
        "",
        "Scenarios are synthetic (random locations and urgencies), so these numbers show the *relative* "
        "benefit of optimal assignment, not real-world response times.",
    ]
    out = HERE / "RESULTS.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print(f"\nWrote {out}")


if __name__ == "__main__":
    main()
